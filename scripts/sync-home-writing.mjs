#!/usr/bin/env node
// Regenerates the Writing section of the static v2 home page (public/v2/index.html)
// from src/data/posts.ts and src/app/research/articles.ts, so the home page and
// /blog never drift. Runs automatically before `npm run build` (prebuild), and can
// be run by hand: `node scripts/sync-home-writing.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

// The data files are plain object literals behind a typed export; take the
// array literal and evaluate it as JS (no TypeScript inside the literal).
function arrayLiteral(src, name) {
  const start = src.indexOf(`export const ${name}`);
  if (start < 0) throw new Error(`${name} not found`);
  const open = src.indexOf("[", src.indexOf("=", start));
  let depth = 0, i = open;
  for (; i < src.length; i++) {
    if (src[i] === "[") depth++;
    else if (src[i] === "]" && --depth === 0) break;
  }
  return new Function(`return ${src.slice(open, i + 1)};`)();
}

const POSTS = arrayLiteral(read("src/data/posts.ts"), "POSTS");
const PAPERS = arrayLiteral(read("src/app/research/articles.ts"), "ARTICLES").filter((a) => a.status !== "superseded");

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const month = (iso) => MONTHS[Number(iso.split("-")[1]) - 1];
const kind = (slug) => (slug === "k8s-local-llm" ? "guide" : "note");
const meter = '<span class="meter" aria-hidden="true"><i class="on"></i><i class="on"></i><i class="on"></i><i class="on"></i><i class="on"></i></span>';

const [latest, ...rest] = POSTS;
const source = latest.slug === "k8s-local-llm" ? '<a href="https://github.com/AlexsJones/axjns-k8s-local-llm" target="_blank" rel="noopener">source ↗</a>' : "";
const html = `      <div class="sec-head"><h2>Writing</h2><span class="label">field notes · research · what came out of the work</span></div>
      <p class="lede">Notes from work in progress and the longer papers behind them: <b>AI agents, distributed systems, and the things that break.</b></p>
      <div class="cur">
        <div class="v"><b>${month(latest.isoDate)}</b><span>latest ${kind(latest.slug)}</span><span>${esc(latest.date)}</span><span>Nº ${String(POSTS.length).padStart(2, "0")}</span></div>
        <div class="t">
          <h3>${esc(latest.title)}</h3>
          <p>${esc(latest.description)}</p>
          <div class="links"><a class="solid" href="/blog/${latest.slug}">read the ${kind(latest.slug)}</a>${source}</div>
        </div>
      </div>
      <div class="sec-sub"><span class="label">field notes · dispatch ledger</span><span class="label">${POSTS.length} entries</span></div>
      <div class="ledger" aria-label="Field notes">
${rest.map((p, i) => `        <div class="row"><span class="v">${String(rest.length - i).padStart(2, "0")}</span><span><a class="ti" href="/blog/${p.slug}">${esc(p.title)}</a><span class="ds">${esc(p.description)}</span></span><span class="st">${month(p.isoDate)} ${p.isoDate.slice(0, 4)} · ${kind(p.slug)}</span></div>`).join("\n")}
      </div>
      <div class="sec-sub"><span class="label">research papers · revision ledger</span><span class="label">${PAPERS.length} current</span></div>
      <div class="ledger" aria-label="Research papers">
${PAPERS.map((a) => `        <div class="row"><span class="v">${esc(a.version ?? a.type)} ${meter}</span><span><a class="ti" href="/research/${a.slug}">${esc(a.title)}</a><span class="ds">${esc(a.description)}</span></span><span class="st">${esc(a.date)} · ${a.type}</span></div>`).join("\n")}
      </div>
      <p class="more"><a href="/blog">All writing →</a></p>`;

const file = join(root, "public/v2/index.html");
const page = readFileSync(file, "utf8");
const A = "<!-- writing:start (generated by scripts/sync-home-writing.mjs; edit src/data/posts.ts) -->";
const B = "<!-- writing:end -->";
const s = page.indexOf(A), e = page.indexOf(B);
if (s < 0 || e < 0) throw new Error("writing markers not found in public/v2/index.html");
const next = page.slice(0, s + A.length) + "\n" + html + "\n      " + page.slice(e);
if (next !== page) writeFileSync(file, next);
console.log(`home Writing: ${POSTS.length} posts, ${PAPERS.length} papers${next === page ? " (unchanged)" : " (updated)"}`);
